def _stable_note(
    entry: Entry,
    axis: str,
    status: str,
    *,
    default: Attempt,
    enabled: Attempt | None,
) -> str:
    if status == CONDITIONAL and axis == "categorical" and entry.name == "KnockoffSelector":
        return (
            'baseline `cat_encoding="none"` rejects string/category columns; '
            '`cat_encoding="loo_logit"` completes with a UserWarning and '
            "`fdr_control='none'` because supervised encoding drops the Model-X claim"
        )
    if status == CONDITIONAL and axis == "categorical" and entry.name == "ModelSelector":
        return (
            "the disclosed Ridge baseline cannot consume string columns; a "
            "width-preserving sklearn OrdinalEncoder pipeline with "
            "`importance='permutation'` completes. Categorical handling is "
            "estimator-dependent and is not a ModelSelector encoding default"
        )
    if status == CONDITIONAL and axis == "categorical":
        return (
            'baseline `cat_encoding="none"` rejects string/category columns; '
            '`cat_encoding="target_cv"` encodes them without extras'
        )
    if status == CONDITIONAL and axis in {"groups", "time"}:
        if entry.name == "ModelSelector":
            return (
                "an explicit integer `n_features_to_select` rejects unused "
                f"`{axis}` metadata; a searched count grid with the default "
                f"reusable `{axis}` CV is accepted"
            )
        return (
            "fixed-k baseline calls reject row context; "
            f'`k="auto"` with evaluate `{axis}` splits is accepted'
        )
    if status == SUPPORTED and axis == "sample_weight" and entry.name == "select_cached":
        return (
            "weights belong on `build_cache(X, sample_weight=w, subsample=None)`; "
            "`select_cached` has no call-time `sample_weight` because the cache "
            "already stores row weights"
        )
    if status == SUPPORTED and axis in {"categorical", "datetime_timedelta"} and (
        entry.name == "permutation_importance"
    ):
        return (
            "`permutation_importance` forwards X to the fitted model; with a "
            "dtype-tolerant fitted estimator the public call completes. Support "
            "is model-dependent"
        )
    if status == SUPPORTED and axis == "datetime_timedelta" and entry.name == "smart_sample":
        return (
            "the baseline call completes after coercing datetime/timedelta "
            "feature columns to epoch-scale float32 values, which can be "
            "lossy; convert them to numeric features explicitly"
        )
    if status == SUPPORTED and axis == "categorical":
        return "string/category columns are consumed by the seeded baseline call"
    if status == SUPPORTED and axis == "sample_weight":
        return "sample_weight is accepted on the seeded baseline call"
    if status == SUPPORTED and axis in {"groups", "time"}:
        if entry.name == "smart_sample":
            col = "group_col" if axis == "groups" else "time_col"
            return (
                f"`{axis}` is accepted as `{col}` on `SmartSamplerConfig`, "
                f"not as a `{axis}=` array argument"
            )
        return f"`{axis}` is accepted on the seeded baseline call"
    if status == SUPPORTED:
        return "seeded, bounded baseline call completed on the tiny fixture"
    if status == DEPENDENCY_GATED:
        if entry.name == "select_boruta_shap" and axis == "categorical":
            return (
                'baseline `cat_encoding="none"` rejects string/category columns; '
                '`cat_encoding="target_cv"` is required, and the SHAP backend '
                "then needs CatBoost or the `shap` package with an explicit "
                "compatible estimator"
            )
        if entry.name in CATBOOST_ENTRIES:
            return (
                "requires the optional `catboost` extra; installing it unlocks "
                "this axis"
            )
        return STABLE_EXTRA_NOTES[entry.name]
    if axis == "datetime_timedelta":
        return (
            "datetime/timedelta feature columns are rejected; convert them to "
            "numeric features explicitly"
        )
    if axis == "sparse":
        if entry.name == "permutation_importance":
            return (
                "sparse matrices are rejected independently of the fitted model; "
                "X must be a 2D dense array or pandas DataFrame"
            )
        if entry.name == "smart_sample":
            return "requires a pandas DataFrame; sparse input is rejected"
        return (
            "sparse input is rejected; pass a dense NumPy array or pandas DataFrame"
        )
    if axis == "categorical":
        if entry.name in {"select_fdr", "select_cached"}:
            return (
                "non-numeric columns are rejected; encode categoricals before "
                "the Gaussian estimator"
            )
        if entry.name == "KnockoffSelector":
            return (
                'baseline `cat_encoding="none"` rejects string/category columns; '
                "`target_cv` is not accepted"
            )
        if entry.name in {
            "StabilitySelector",
            "stability_regression",
            "stability_classif",
            "Stabilized",
            "smart_sample",
        }:
            return "string/category columns are not accepted as numeric features"
        return "string/category columns are rejected on the seeded baseline call"
    if axis in {"groups", "time"}:
        if entry.name == "select_fdr":
            return f"the public function has no `{axis}` argument"
        if entry.name == "KnockoffSelector":
            if axis == "groups":
                return (
                    "row groups are rejected; use `feature_groups` for grouped "
                    "discoveries"
                )
            return "time-aware fitting is rejected"
        if entry.name == "select_cached":
            return (
                "`select_cached` has no groups or time argument; row context is "
                "not part of the cache-backed selector"
            )
        if entry.name == "Stabilized":
            return (
                f"`{axis}` is consumed by resample='blocks' (which needs both "
                "groups and time) or forwarded to bases that accept row context; "
                "unused row metadata is rejected"
            )
        return f"`{axis}` is rejected on the seeded baseline call"
    if axis == "numeric_ndarray":
        if entry.name == "smart_sample":
            return "requires a pandas DataFrame; ndarray input is rejected"
        return "ndarray input is rejected; pass a pandas DataFrame"
    if axis == "sample_weight":
        if entry.name == "smart_sample":
            return (
                "there is no input `sample_weight` argument; the sampler writes "
                "its own `sample_weight` column"
            )
        return "sample_weight is rejected on the seeded baseline call"
    return "the public call raised"


def classify_cell(entry: Entry, axis: str) -> Cell:
    payload = make_payload(axis)
    default = _run(lambda: entry.call(payload))
    if _is_missing_dependency(default, entry.extra):
        enabled = None
        if entry.name == "select_boruta_shap":
            enabled = _shap_probe(entry, payload)
        return Cell(
            entry.name,
            axis,
            DEPENDENCY_GATED,
            _stable_note(
                entry, axis, DEPENDENCY_GATED, default=default, enabled=enabled
            ),
            default,
            enabled,
        )

    enabled_mode = _enabled_mode(axis, entry)
    enabled = None
    if not default.ok and enabled_mode is not None:
        enabled = _run(lambda: entry.call(payload, **enabled_mode))
        if enabled.ok:
            return Cell(
                entry.name,
                axis,
                CONDITIONAL,
                _stable_note(
                    entry, axis, CONDITIONAL, default=default, enabled=enabled
                ),
                default,
                enabled,
            )
        if _is_missing_dependency(enabled, entry.extra):
            if entry.name == "select_boruta_shap":
                enabled = _shap_probe(entry, payload, enabled_mode)
            return Cell(
                entry.name,
                axis,
                DEPENDENCY_GATED,
                _stable_note(
                    entry,
                    axis,
                    DEPENDENCY_GATED,
                    default=default,
                    enabled=enabled,
                ),
                default,
                enabled,
            )

    if default.ok:
        return Cell(
            entry.name,
            axis,
            SUPPORTED,
            _stable_note(entry, axis, SUPPORTED, default=default, enabled=None),
            default,
        )

    return Cell(
        entry.name,
        axis,
        REJECTED,
        _stable_note(entry, axis, REJECTED, default=default, enabled=enabled),
        default,
        enabled,
    )


def probe_all() -> list[Cell]:
    _ensure_import_path()
    cells = []
    for entry in entries():
        for axis in AXES:
            cells.append(classify_cell(entry, axis))
    return cells


STABLE_EXTRA_NOTES = {
    "select_boruta_shap": (
        "the default SHAP backend needs CatBoost; without CatBoost, an explicit "
        "non-CatBoost estimator still requires the optional `shap` package"
    ),
}


def publish_cell(cell: Cell, entry: Entry) -> Cell:
    """Publish one environment-stable contract per extra-gated entry.

    For the three CatBoost selectors, publish the known post-install contract
    in every environment: ndarray/sparse/datetime-timedelta are rejected;
    DataFrame/categorical/weights/groups/time are dependency-gated. ``dep``
    means installing the extra can unlock the axis.
    """
    if entry.name in CATBOOST_ENTRIES:
        status = CATBOOST_PUBLISHED_STATUS[cell.axis]
        return Cell(
            cell.entry,
            cell.axis,
            status,
            _stable_note(
                entry,
                cell.axis,
                status,
                default=cell.default,
                enabled=cell.enabled,
            ),
            cell.default,
            cell.enabled,
        )
    if entry.extra is None or cell.status == REJECTED:
        return cell
    return Cell(
        cell.entry,
        cell.axis,
        DEPENDENCY_GATED,
        _stable_note(
            entry,
            cell.axis,
            DEPENDENCY_GATED,
            default=cell.default,
            enabled=cell.enabled,
        ),
        cell.default,
        cell.enabled,
    )


def probe_published() -> list[Cell]:
    _ensure_import_path()
    by_name = {entry.name: entry for entry in entries()}
    return [publish_cell(cell, by_name[cell.entry]) for cell in probe_all()]


def _status_grid(cells: list[Cell]) -> dict[tuple[str, str], Cell]:
    return {(cell.entry, cell.axis): cell for cell in cells}


def render_table(cells: list[Cell]) -> str:
    grid = _status_grid(cells)
    header = ["entry", *[AXIS_HEADERS[axis] for axis in AXES]]
    lines = [
        "| " + " | ".join(header) + " |",
        "| --- | " + " | ".join(["---"] * len(AXES)) + " |",
    ]
    seen: list[str] = []
    for cell in cells:
        if cell.entry not in seen:
            seen.append(cell.entry)
    for name in seen:
        row = [f"`{name}`"]
        for axis in AXES:
            row.append(STATUS_LABELS[grid[(name, axis)].status])
        lines.append("| " + " | ".join(row) + " |")
    return "\n".join(lines)


def render_notes(cells: list[Cell]) -> str:
    lines = [
        "| entry | axis | status | observed behavior |",
        "| --- | --- | --- | --- |",
    ]
    for cell in cells:
        if cell.status == SUPPORTED and cell.axis in {
            "numeric_ndarray",
            "numeric_dataframe",
        }:
            continue
        if (
            cell.status == SUPPORTED
            and cell.axis == "sample_weight"
            and cell.entry != "select_cached"
        ):
            continue
        lines.append(
            "| "
            + " | ".join(
                (
                    f"`{cell.entry}`",
                    AXIS_HEADERS[cell.axis],
                    cell.status,
                    cell.note.replace("|", "\\|"),
                )
            )
            + " |"
        )
    return "\n".join(lines)


