@dataclass
class Payload:
    X: object
    y: np.ndarray
    y_binary: np.ndarray
    sample_weight: np.ndarray | None = None
    groups: np.ndarray | None = None
    time: np.ndarray | None = None
    cat_features: list[str] | None = None
    feature_names: list[str] = field(default_factory=list)
    frame: pd.DataFrame | None = None


def _base_numeric(n: int = N_ROWS, p: int = N_FEATURES) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    rng = np.random.default_rng(SEED)
    X = rng.normal(size=(n, p))
    X[:, 0] = np.linspace(-1.0, 1.0, n)
    y = X[:, 0] + 0.15 * X[:, 1] + 0.05 * rng.normal(size=n)
    y_binary = (y > np.median(y)).astype(np.int64)
    return X, y, y_binary


def _names(p: int = N_FEATURES) -> list[str]:
    return [f"x{i}" for i in range(p)]


def make_payload(axis: str) -> Payload:
    X, y, y_binary = _base_numeric()
    names = _names()
    n = X.shape[0]
    groups = np.repeat(np.arange(4, dtype=np.int64), n // 4)
    time = np.arange(n, dtype=np.int64)
    weights = np.linspace(0.5, 1.5, n)
    frame = pd.DataFrame(X, columns=names)

    if axis == "numeric_ndarray":
        return Payload(X=X, y=y, y_binary=y_binary, feature_names=names)
    if axis == "numeric_dataframe":
        return Payload(
            X=frame.copy(),
            y=y,
            y_binary=y_binary,
            feature_names=names,
            frame=frame.copy(),
        )
    if axis == "categorical":
        cats = np.array(["red", "blue", "green", "gold"], dtype=object)
        labeled = frame.copy()
        labeled["city"] = cats[np.arange(n) % 4]
        return Payload(
            X=labeled,
            y=y,
            y_binary=y_binary,
            feature_names=list(labeled.columns),
            cat_features=["city"],
            frame=labeled,
        )
    if axis == "sparse":
        return Payload(
            X=sparse.csr_matrix(X),
            y=y,
            y_binary=y_binary,
            feature_names=names,
        )
    if axis == "datetime_timedelta":
        labeled = frame.copy()
        labeled["when"] = pd.date_range("2024-01-01", periods=n, freq="D")
        labeled["elapsed"] = pd.to_timedelta(np.arange(n), unit="h")
        return Payload(
            X=labeled,
            y=y,
            y_binary=y_binary,
            feature_names=list(labeled.columns),
            frame=labeled,
        )
    if axis == "sample_weight":
        return Payload(
            X=frame.copy(),
            y=y,
            y_binary=y_binary,
            sample_weight=weights,
            feature_names=names,
            frame=frame.copy(),
        )
    if axis == "groups":
        labeled = frame.copy()
        labeled["entity"] = groups
        return Payload(
            X=frame.copy(),
            y=y,
            y_binary=y_binary,
            groups=groups,
            feature_names=names,
            frame=labeled,
        )
    if axis == "time":
        stamps = pd.date_range("2024-01-01", periods=n, freq="D")
        labeled = frame.copy()
        labeled["as_of"] = stamps
        return Payload(
            X=frame.copy(),
            y=y,
            y_binary=y_binary,
            time=stamps.to_numpy(),
            feature_names=names,
            frame=labeled,
        )
    raise ValueError(f"unknown axis {axis!r}")


def _run(call) -> Attempt:
    with warnings.catch_warnings(record=True) as caught:
        warnings.simplefilter("always")
        try:
            call()
        except Exception as exc:
            return Attempt(
                ok=False,
                error=f"{type(exc).__name__}: {exc}",
                warnings=tuple(str(item.message) for item in caught),
            )
        return Attempt(
            ok=True,
            warnings=tuple(str(item.message) for item in caught),
        )


def _is_missing_dependency(attempt: Attempt, extra: str | None) -> bool:
    if extra is None or attempt.ok or attempt.error is None:
        return False
    text = attempt.error.lower()
    if extra == "catboost":
        return "catboost" in text and (
            text.startswith("importerror")
            or "modulenotfounderror" in text
            or "requires catboost" in text
        )
    if extra == "shap":
        # Do not match the substring "import" inside "importance".
        return "shap" in text and (
            text.startswith("importerror")
            or "modulenotfounderror" in text
            or "shap package" in text
        )
    if extra == "category_encoders":
        return "category_encoders" in text or "categorical encoding" in text
    return extra.lower() in text and (
        text.startswith("importerror") or "modulenotfounderror" in text
    )


def _accepts(callable_obj, name: str) -> bool:
    try:
        return name in inspect.signature(callable_obj).parameters
    except (TypeError, ValueError):
        return False


def _auto_k_config(*, groups: bool) -> object:
    from sift import AutoKConfig

    return AutoKConfig(
        k_method="evaluate",
        strategy="group_cv" if groups else "time_holdout",
        min_k=1,
        max_k=K,
        n_splits=2,
        val_frac=0.25,
    )


def _y(payload: Payload, binary: bool) -> np.ndarray:
    return payload.y_binary if binary else payload.y


def _filter_function_kwargs(
    fn,
    payload: Payload,
    *,
    binary: bool,
    auto: bool,
    cat_encoding: str | None,
    extra: dict,
) -> dict:
    kwargs = {
        "k": "auto" if auto else K,
        "verbose": False,
        "subsample": None,
        "random_state": SEED,
        **extra,
    }
    if _accepts(fn, "task") and "task" not in kwargs and not binary:
        kwargs["task"] = "regression"
    if payload.sample_weight is not None:
        kwargs["sample_weight"] = payload.sample_weight
    if payload.groups is not None:
        kwargs["groups"] = payload.groups
    if payload.time is not None:
        kwargs["time"] = payload.time
    if cat_encoding is not None:
        kwargs["cat_encoding"] = cat_encoding
        if payload.cat_features is not None:
            kwargs["cat_features"] = payload.cat_features
    if auto:
        kwargs["auto_k_config"] = _auto_k_config(groups=payload.groups is not None)
    return kwargs


def call_filter_function(
    fn,
    payload: Payload,
    *,
    binary: bool = False,
    auto: bool = False,
    cat_encoding: str | None = None,
    extra: dict | None = None,
) -> None:
    kwargs = _filter_function_kwargs(
        fn,
        payload,
        binary=binary,
        auto=auto,
        cat_encoding=cat_encoding,
        extra=extra or {},
    )
    fn(payload.X, _y(payload, binary), **kwargs)


def call_filter_class(
    cls,
    payload: Payload,
    *,
    binary: bool = False,
    auto: bool = False,
    cat_encoding: str | None = None,
    extra: dict | None = None,
) -> None:
    ctor = {
        "k": "auto" if auto else K,
        "verbose": False,
        "subsample": None,
        "random_state": SEED,
        **(extra or {}),
    }
    if _accepts(cls, "task") and "task" not in ctor and not binary:
        ctor["task"] = "regression"
    if cat_encoding is not None:
        ctor["cat_encoding"] = cat_encoding
        if payload.cat_features is not None:
            ctor["cat_features"] = payload.cat_features
    if auto:
        ctor["auto_k_config"] = _auto_k_config(groups=payload.groups is not None)
    fit_kwargs = {}
    if payload.sample_weight is not None:
        fit_kwargs["sample_weight"] = payload.sample_weight
    if payload.groups is not None:
        fit_kwargs["groups"] = payload.groups
    if payload.time is not None:
        fit_kwargs["time"] = payload.time
    cls(**ctor).fit(payload.X, _y(payload, binary), **fit_kwargs)


