def call_knockoff_selector(
    payload: Payload,
    *,
    cat_encoding: str | None = None,
) -> None:
    from sift import KnockoffSelector

    ctor = {"q": 0.5, "n_draws": 1, "verbose": False, "random_state": SEED}
    if cat_encoding is not None:
        ctor["cat_encoding"] = cat_encoding
        if payload.cat_features is not None:
            ctor["cat_features"] = payload.cat_features
    fit_kwargs = {}
    if payload.sample_weight is not None:
        fit_kwargs["sample_weight"] = payload.sample_weight
    if payload.groups is not None:
        fit_kwargs["groups"] = payload.groups
    if payload.time is not None:
        fit_kwargs["time"] = payload.time
    y = payload.y_binary if cat_encoding == "loo_logit" else payload.y
    KnockoffSelector(**ctor).fit(payload.X, y, **fit_kwargs)


def call_boruta(
    payload: Payload,
    *,
    shap: bool = False,
    cat_encoding: str | None = None,
    as_class: bool = False,
    estimator=None,
) -> None:
    from sift import BorutaSelector, select_boruta, select_boruta_shap

    kwargs = {
        "max_iter": 1,
        "n_estimators": 4,
        "early_stop_rounds": 1,
        "resolve_tentative": False,
        "verbose": False,
        "random_state": SEED,
    }
    if cat_encoding is not None:
        kwargs["cat_encoding"] = cat_encoding
        if payload.cat_features is not None:
            kwargs["cat_features"] = payload.cat_features
    if estimator is not None:
        kwargs["estimator"] = estimator
    if payload.sample_weight is not None:
        kwargs["sample_weight"] = payload.sample_weight
    if payload.groups is not None:
        kwargs["groups"] = payload.groups
    if payload.time is not None:
        kwargs["time"] = payload.time
    if shap:
        select_boruta_shap(payload.X, payload.y, **kwargs)
        return
    if as_class:
        sample_weight = kwargs.pop("sample_weight", None)
        groups = kwargs.pop("groups", None)
        time = kwargs.pop("time", None)
        BorutaSelector(**kwargs).fit(
            payload.X,
            payload.y,
            sample_weight=sample_weight,
            groups=groups,
            time=time,
        )
        return
    select_boruta(payload.X, payload.y, **kwargs)


def call_stability(
    payload: Payload,
    *,
    kind: str,
) -> None:
    from sift import StabilitySelector, stability_classif, stability_regression

    common = {
        "n_bootstrap": 2,
        "n_jobs": 1,
        "alpha": 1.0,
        "verbose": False,
        "random_state": SEED,
        "store_coefs": False,
    }
    fit_kwargs = {}
    if payload.sample_weight is not None:
        fit_kwargs["sample_weight"] = payload.sample_weight
    if payload.groups is not None:
        fit_kwargs["groups"] = payload.groups
    if payload.time is not None:
        fit_kwargs["time"] = payload.time
    y = payload.y_binary if kind == "classif" else payload.y
    if kind == "selector":
        StabilitySelector(task="regression", **common).fit(payload.X, y, **fit_kwargs)
        return
    fn = stability_classif if kind == "classif" else stability_regression
    fn(payload.X, y, k=K, **common, **fit_kwargs)


def _width_preserving_ordinal_ridge():
    """Encode non-numeric columns without expanding width, then Ridge.

    ``make_column_selector`` follows whatever columns the current fit still
    has, so RFE subsets keep working. Permutation importance ranks the raw
    input columns. This is a disclosed ``ModelSelector`` probe pipeline, not
    a SIFT default.
    """
    from sklearn.compose import ColumnTransformer, make_column_selector
    from sklearn.linear_model import Ridge
    from sklearn.pipeline import make_pipeline
    from sklearn.preprocessing import OrdinalEncoder

    encoder = ColumnTransformer(
        [
            (
                "cat",
                OrdinalEncoder(
                    handle_unknown="use_encoded_value",
                    unknown_value=-1,
                ),
                make_column_selector(dtype_exclude=np.number),
            )
        ],
        remainder="passthrough",
        verbose_feature_names_out=False,
    )
    return make_pipeline(encoder, Ridge())


def call_model_selector(payload: Payload, **mode) -> None:
    from sklearn.linear_model import Ridge
    from sift import ModelSelector

    search_counts = bool(mode.get("search_counts"))
    encode_categorical = bool(mode.get("encode_categorical"))
    if encode_categorical:
        if not isinstance(payload.X, pd.DataFrame):
            raise TypeError("categorical ModelSelector probe requires a DataFrame")
        estimator = _width_preserving_ordinal_ridge()
        importance = "permutation"
    else:
        estimator = Ridge()
        importance = "auto"
    selector = ModelSelector(
        estimator,
        n_features_to_select=[1, K] if search_counts else K,
        importance=importance,
        random_state=SEED,
        verbose=False,
    )
    kwargs = {}
    if payload.sample_weight is not None:
        kwargs["sample_weight"] = payload.sample_weight
    if payload.groups is not None:
        kwargs["groups"] = payload.groups
    if payload.time is not None:
        kwargs["time"] = payload.time
    selector.fit(payload.X, payload.y, **kwargs)


def call_stabilized(payload: Payload, **_mode) -> None:
    from sift import CEFSPlusSelector, Stabilized

    inner = CEFSPlusSelector(k=K, verbose=False, subsample=None, random_state=SEED)
    estimator = Stabilized(
        inner,
        n_resamples=2,
        resample="half",
        threshold=0.0,
        random_state=SEED,
        verbose=False,
    )
    kwargs = {}
    if payload.sample_weight is not None:
        kwargs["sample_weight"] = payload.sample_weight
    if payload.groups is not None:
        kwargs["groups"] = payload.groups
    if payload.time is not None:
        kwargs["time"] = payload.time
    estimator.fit(payload.X, payload.y, **kwargs)


def call_permutation(payload: Payload) -> None:
    from sift import permutation_importance

    model = _DtypeTolerantRegressor().fit(payload.X, payload.y)
    kwargs = {"n_repeats": 1, "n_jobs": 1, "random_state": SEED}
    if payload.sample_weight is not None:
        kwargs["sample_weight"] = payload.sample_weight
    if payload.groups is not None:
        kwargs["groups"] = payload.groups
    if payload.time is not None:
        kwargs["time"] = payload.time
    permutation_importance(model, payload.X, payload.y, **kwargs)


def call_smart_sample(payload: Payload) -> None:
    from sift import smart_sample

    if not isinstance(payload.X, pd.DataFrame):
        smart_sample(
            payload.X,
            payload.feature_names,
            "y",
            random_state=SEED,
            verbose=False,
            sample_frac=0.5,
            min_per_group=1,
        )
        return

    df = payload.frame.copy() if payload.frame is not None else payload.X.copy()
    y_col = "y"
    df[y_col] = payload.y
    feature_cols = [name for name in df.columns if name not in {y_col, "entity", "as_of"}]
    kwargs = {
        "random_state": SEED,
        "verbose": False,
        "sample_frac": 0.5,
        "min_per_group": 1,
    }
    if payload.groups is not None:
        kwargs["group_col"] = "entity"
    if payload.time is not None:
        kwargs["time_col"] = "as_of"
    if payload.sample_weight is not None:
        kwargs["sample_weight"] = payload.sample_weight
    smart_sample(df, feature_cols, y_col, **kwargs)


def call_select_cached(payload: Payload) -> None:
    from sift import build_cache, select_cached

    cache_kwargs = {"subsample": None}
    if payload.sample_weight is not None:
        cache_kwargs["sample_weight"] = payload.sample_weight
    cache = build_cache(payload.X, **cache_kwargs)
    kwargs = {"k": K}
    if payload.groups is not None:
        kwargs["groups"] = payload.groups
    if payload.time is not None:
        kwargs["time"] = payload.time
    select_cached(cache, payload.y, **kwargs)


def call_catboost(
    payload: Payload,
    *,
    kind: str,
) -> None:
    import sift

    kwargs = {
        "k": K,
        "n_splits": 2,
        "prefilter_k": None,
        "n_estimators": 8,
        "algorithm": "prediction",
        "steps": 1,
        "train_early_stopping_rounds": 1,
        "n_jobs": 1,
        "random_state": SEED,
        "verbose": False,
    }
    if payload.sample_weight is not None:
        kwargs["sample_weight"] = payload.sample_weight
    if payload.groups is not None:
        kwargs["groups"] = payload.groups
    if payload.time is not None:
        kwargs["time"] = payload.time
    if kind == "select":
        sift.catboost_select(payload.X, _y(payload, False), task="regression", **kwargs)
        return
    if kind == "regression":
        sift.catboost_regression(payload.X, payload.y, **kwargs)
        return
    sift.catboost_classif(payload.X, payload.y_binary, **kwargs)


