def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="exit 1 if docs/data-type-support.md does not match a live probe",
    )
    args = parser.parse_args(argv)
    try:
        page = expected_page()
    except Exception:
        traceback.print_exc()
        return 2
    if args.check:
        current = DOC.read_text(encoding="utf-8")
        if current != page:
            print(f"{DOC.relative_to(ROOT)} is stale; rerun without --check", file=sys.stderr)
            return 1
        return 0
    DOC.write_text(page, encoding="utf-8")
    print(f"wrote {DOC.relative_to(ROOT)}")
    return 0


