def _enabled_mode(axis: str, entry: Entry) -> dict | None:
    if axis == "categorical" and entry.supports_target_cv:
        return {"cat_encoding": "target_cv"}
    if axis == "categorical" and entry.name == "KnockoffSelector":
        return {"cat_encoding": "loo_logit"}
    if axis == "categorical" and entry.name == "ModelSelector":
        return {"encode_categorical": True}
    if axis in {"groups", "time"} and entry.supports_auto_k:
        return {"auto": True}
    if axis in {"groups", "time"} and entry.name == "ModelSelector":
        return {"search_counts": True}
    return None


def _shap_estimator():
    return RandomForestRegressor(n_estimators=4, max_depth=2, random_state=SEED)


def _shap_probe(entry: Entry, payload: Payload, enabled_mode: dict | None = None) -> Attempt:
    kwargs = {"estimator": _shap_estimator()}
    if enabled_mode:
        kwargs.update(enabled_mode)
    return _run(lambda: entry.call(payload, **kwargs))


