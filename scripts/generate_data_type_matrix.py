@dataclass(frozen=True)
class Attempt:
    ok: bool
    error: str | None = None
    warnings: tuple[str, ...] = ()

    @property
    def summary(self) -> str:
        if self.ok:
            return "completed"
        assert self.error is not None
        first = self.error.strip().splitlines()[0]
        return first[:180]


class _DtypeTolerantRegressor:
    """Fitted stand-in that accepts mixed-dtype X so SIFT is the code under test.

    sklearn numeric estimators reject string and datetime columns in ``fit``,
    which would never reach ``permutation_importance``. This probe vehicle is
    a legitimate fitted estimator with ``predict``; it does not encode or
    select features.
    """

    def fit(self, X, y):
        y_arr = np.asarray(y, dtype=np.float64).reshape(-1)
        self.constant_ = float(np.mean(y_arr)) if y_arr.size else 0.0
        return self

    def predict(self, X):
        n = int(X.shape[0])
        return np.full(n, self.constant_, dtype=np.float64)


